-- 0. Включение необходимых криптографических расширений
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ============================================================================
-- 1. ТАБЛИЦЫ БАЗЫ ДАННЫХ
-- ============================================================================

-- 1.1. База 20 героев колледжа
CREATE TABLE IF NOT EXISTS public.heroes_database (
    id VARCHAR(100) PRIMARY KEY,
    name TEXT NOT NULL,
    plaque VARCHAR(20) DEFAULT 'general',
    spec_tag VARCHAR(50),
    dates JSONB DEFAULT '{}'::jsonb,
    education JSONB DEFAULT '{}'::jsonb,
    military JSONB DEFAULT '{}'::jsonb,
    awards JSONB DEFAULT '[]'::jsonb,
    deed TEXT,
    quote TEXT,
    media JSONB DEFAULT '{}'::jsonb,
    map_coords JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.2. Мемориальные счетчики свечей, цветов и молитв памяти
CREATE TABLE IF NOT EXISTS public.memorial_counters (
    hero_id VARCHAR(100) PRIMARY KEY,
    candles INTEGER DEFAULT 0 CHECK (candles >= 0),
    flowers INTEGER DEFAULT 0 CHECK (flowers >= 0),
    prayers INTEGER DEFAULT 0 CHECK (prayers >= 0),
    last_updated TIMESTAMPTZ DEFAULT NOW()
);

-- 1.3. Книга Памяти и соболезнований (Стена Памяти)
CREATE TABLE IF NOT EXISTS public.guestbook_tributes (
    id VARCHAR(100) PRIMARY KEY,
    author VARCHAR(255) NOT NULL,
    role VARCHAR(50) DEFAULT 'guest',
    role_label VARCHAR(150),
    dedication_id VARCHAR(100) DEFAULT 'general',
    dedication_name VARCHAR(255),
    message TEXT NOT NULL,
    theme VARCHAR(50) DEFAULT 'theme-parchment',
    date VARCHAR(50),
    flames INTEGER DEFAULT 1 CHECK (flames >= 0),
    is_pinned BOOLEAN DEFAULT FALSE,
    is_verified BOOLEAN DEFAULT FALSE,
    visit_id VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.4. Результаты тестирования и исторического квеста (Зал Славы)
CREATE TABLE IF NOT EXISTS public.quiz_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name VARCHAR(255) NOT NULL,
    group_name VARCHAR(100),
    score INTEGER NOT NULL CHECK (score >= 0 AND score <= 20),
    total_questions INTEGER DEFAULT 10,
    duration_seconds INTEGER DEFAULT 0,
    client_fingerprint VARCHAR(255),
    completed_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.5. Официальный реестр выданных сертификатов с хэшем SHA-256
CREATE TABLE IF NOT EXISTS public.certificates_registry (
    serial VARCHAR(100) PRIMARY KEY,
    student_name VARCHAR(255) NOT NULL,
    group_name VARCHAR(100),
    specialty VARCHAR(255),
    nomination VARCHAR(255),
    issue_date VARCHAR(50),
    crypto_hash VARCHAR(255),
    qr_data TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.6. Профиль пользователя, воинские чины и прогресс XP
CREATE TABLE IF NOT EXISTS public.user_achievements (
    user_id VARCHAR(100) PRIMARY KEY,
    xp INTEGER DEFAULT 0 CHECK (xp >= 0),
    rank_id VARCHAR(50) DEFAULT 'private',
    rank_title VARCHAR(100) DEFAULT 'Рядовой',
    unlocked_badges JSONB DEFAULT '[]'::jsonb,
    stats JSONB DEFAULT '{}'::jsonb,
    last_active_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.7. Лог событий получения наград и знаков отличия (27 бейджей)
CREATE TABLE IF NOT EXISTS public.achievement_unlock_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(100) NOT NULL,
    badge_id VARCHAR(100) NOT NULL,
    badge_title VARCHAR(255),
    badge_icon VARCHAR(50),
    xp_reward INTEGER DEFAULT 0,
    unlocked_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.8. Аналитические счетчики посещаемости залов (ФЗ-152, анонимно)
CREATE TABLE IF NOT EXISTS public.hall_analytics_counters (
    hall_id VARCHAR(100) PRIMARY KEY,
    visits INTEGER DEFAULT 0 CHECK (visits >= 0),
    total_dwell_seconds INTEGER DEFAULT 0 CHECK (total_dwell_seconds >= 0),
    interactions INTEGER DEFAULT 0 CHECK (interactions >= 0),
    last_visited_at TIMESTAMPTZ DEFAULT NOW()
);

-- 1.9. Сводные метрики мемориала в реальном времени
CREATE TABLE IF NOT EXISTS public.museum_realtime_metrics (
    metric_key VARCHAR(100) PRIMARY KEY,
    metric_value JSONB DEFAULT '{}'::jsonb,
    description TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

